export function canTransitionOperationState(fromState, toState) {
  const from = String(fromState || "").toUpperCase();
  const to = String(toState || "").toUpperCase();
  const allowed = ALLOWED_TRANSITIONS[from] || [];
  return allowed.includes(to);
}

export function normalizeLifecycleToEditExecutionState(value) {
  const v = String(value || "").trim().toUpperCase();
  if (
    ["DRAFT", "PREVIEWED", "TARGET_FREEZING", "TARGET_FROZEN", "PLANNING", "PLANNED"].includes(v)
  ) return "PLANNED";
  if (v === "PAUSED") return "PAUSED";
  if (["SCHEDULED_PENDING_QUEUE", "SCHEDULED_QUEUED", "QUEUED", "UNDO_QUEUED", "WAITING_FOR_SHOPIFY_SLOT"].includes(v)) return "QUEUED";
  if (v === "EXECUTING") return "DISPATCHING";
  if (["RECONCILE_SUBMITTED", "SHOPIFY_BULK_SUBMITTED", "SHOPIFY_RUNNING"].includes(v)) return "AWAITING_SHOPIFY";
  if (["SHOPIFY_COMPLETED", "INGESTING_RESULTS", "VERIFYING", "MIRROR_UPDATING", "UNDO_RUNNING"].includes(v)) {
    return "FINALIZING";
  }
  if (["COMPLETED", "UNDO_COMPLETED"].includes(v)) return "COMPLETED";
  if (v === "PARTIAL_FAILED") return "PARTIAL";
  if (v === "FAILED") return "FAILED";
  if (v === "CANCELLED") return "CANCELLED";
  return "UNKNOWN";
}
